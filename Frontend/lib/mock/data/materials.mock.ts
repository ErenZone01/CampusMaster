// Helper pour obtenir les matériels d'un cours
export const getMaterialsByCourse = (courseId: string): CourseMaterial[] => {
  return MOCK_MATERIALS.filter(material => material.course_id === courseId)
    .sort((a, b) => a.order - b.order)
}

// Helper pour chercher un matériel par ID
export const findMaterialById = (id: string): CourseMaterial | undefined => {
  return MOCK_MATERIALS.find(material => material.id === id)
}

// Helper pour obtenir les matériels visibles d'un cours
export const getVisibleMaterials = (courseId: string): CourseMaterial[] => {
  return MOCK_MATERIALS.filter(
    material => material.course_id === courseId && material.is_visible
  ).sort((a, b) => a.order - b.order)
}
